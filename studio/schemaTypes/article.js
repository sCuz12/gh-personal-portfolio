import { defineArrayMember, defineField, defineType } from 'sanity';

export const article = defineType({
  name: 'article',
  title: 'Article',
  type: 'document',
  groups: [
    { name: 'content', title: 'Content', default: true },
    { name: 'seo', title: 'SEO' },
  ],
  fields: [
    defineField({ name: 'title', title: 'Title', type: 'string', group: 'content', validation: (rule) => rule.required() }),
    defineField({
      name: 'category',
      title: 'Category',
      description: 'The primary editorial pillar for this article.',
      type: 'string',
      group: 'content',
      options: {
        layout: 'radio',
        list: [
          { title: 'Engineering', value: 'engineering' },
          { title: 'AI Systems', value: 'ai-systems' },
          { title: 'Business', value: 'business' },
          { title: 'Mind & Growth', value: 'mind' },
        ],
      },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'type',
      title: 'Format',
      type: 'string',
      group: 'content',
      initialValue: 'note',
      options: { layout: 'radio', list: [{ title: 'Essay', value: 'essay' }, { title: 'Note', value: 'note' }, { title: 'Log', value: 'log' }] },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'status',
      title: 'Status',
      type: 'string',
      group: 'content',
      initialValue: 'thinking',
      options: { layout: 'radio', list: [{ title: 'Thinking', value: 'thinking' }, { title: 'Tested', value: 'tested' }, { title: 'Shipped', value: 'shipped' }] },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      group: 'content',
      options: { source: 'title', maxLength: 96 },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'excerpt',
      title: 'Excerpt',
      type: 'text',
      rows: 4,
      group: 'content',
      validation: (rule) => rule.required().max(240),
    }),
    defineField({
      name: 'coverImage',
      title: 'Cover image',
      type: 'image',
      group: 'content',
      options: { hotspot: true },
      fields: [
        defineField({ name: 'alt', title: 'Alternative text', type: 'string', validation: (rule) => rule.required() }),
        defineField({ name: 'caption', title: 'Caption', type: 'string' }),
      ],
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'topics',
      title: 'Topics',
      type: 'array',
      group: 'content',
      of: [defineArrayMember({ type: 'reference', to: [{ type: 'topic' }] })],
      validation: (rule) => rule.required().min(1),
    }),
    defineField({ name: 'featured', title: 'Featured article', type: 'boolean', initialValue: false, group: 'content' }),
    defineField({
      name: 'publishedAt',
      title: 'Published at',
      type: 'datetime',
      group: 'content',
      initialValue: () => new Date().toISOString(),
      validation: (rule) => rule.required(),
    }),
    defineField({ name: 'updatedAt', title: 'Last meaningfully updated', type: 'datetime', group: 'content' }),
    defineField({
      name: 'relatedProject',
      title: 'Related project',
      type: 'object',
      group: 'content',
      fields: [
        defineField({ name: 'title', title: 'Project title', type: 'string', validation: (rule) => rule.required() }),
        defineField({ name: 'href', title: 'Case study path', type: 'string', description: 'Example: /work/decree', validation: (rule) => rule.required() }),
      ],
    }),
    defineField({
      name: 'body',
      title: 'Body',
      type: 'array',
      group: 'content',
      of: [
        defineArrayMember({
          type: 'block',
          styles: [
            { title: 'Normal', value: 'normal' },
            { title: 'Heading 2', value: 'h2' },
            { title: 'Heading 3', value: 'h3' },
            { title: 'Quote', value: 'blockquote' },
          ],
          marks: {
            annotations: [
              {
                name: 'link',
                title: 'Link',
                type: 'object',
                fields: [
                  defineField({ name: 'href', title: 'URL', type: 'url', validation: (rule) => rule.uri({ scheme: ['http', 'https', 'mailto'] }) }),
                  defineField({ name: 'blank', title: 'Open in new tab', type: 'boolean', initialValue: false }),
                ],
              },
              {
                name: 'articleLink',
                title: 'Brain article',
                type: 'object',
                fields: [defineField({ name: 'article', title: 'Article', type: 'reference', to: [{ type: 'article' }], validation: (rule) => rule.required() })],
              },
            ],
          },
        }),
        defineArrayMember({
          type: 'image',
          options: { hotspot: true },
          validation: (rule) => rule.required(),
          fields: [
            defineField({ name: 'alt', title: 'Alternative text', type: 'string', validation: (rule) => rule.required() }),
            defineField({ name: 'caption', title: 'Caption', type: 'string' }),
          ],
        }),
        defineArrayMember({ type: 'code', name: 'codeBlock', title: 'Code block', options: { withFilename: true } }),
        defineArrayMember({ type: 'callout' }),
        defineArrayMember({
          type: 'object',
          name: 'divider',
          title: 'Divider',
          fields: [defineField({ name: 'style', type: 'string', hidden: true, initialValue: 'line' })],
          preview: { prepare: () => ({ title: 'Divider' }) },
        }),
      ],
      validation: (rule) => rule.required().min(1),
    }),
    defineField({
      name: 'seo',
      title: 'Search and social metadata',
      type: 'object',
      group: 'seo',
      fields: [
        defineField({ name: 'title', title: 'Meta title', type: 'string', validation: (rule) => rule.max(60) }),
        defineField({ name: 'description', title: 'Meta description', type: 'text', rows: 3, validation: (rule) => rule.max(160) }),
        defineField({ name: 'image', title: 'Social image', type: 'image', options: { hotspot: true } }),
      ],
    }),
  ],
  orderings: [{ title: 'Publication date', name: 'publishedAtDesc', by: [{ field: 'publishedAt', direction: 'desc' }] }],
  preview: {
    select: { title: 'title', category: 'category', excerpt: 'excerpt', media: 'coverImage' },
    prepare: ({ title, category, excerpt, media }) => ({
      title,
      subtitle: [category, excerpt].filter(Boolean).join(' · '),
      media,
    }),
  },
});
